import os
import re
import pandas as pd
from dotenv import load_dotenv
from functools import cache
from sqlalchemy import create_engine, text
from contextlib import closing
from pathlib import Path
import sqlite3

load_dotenv()


@cache
def _engine_neon():
    """Engine do Neon criada uma única vez, só quando precisar. Sem NEON_DB no
    .env retorna None e a carga fica só no SQLite."""
    banco_url = os.getenv("NEON_DB")
    if not banco_url:
        print("Aviso: NEON_DB não definido no .env, gravando só no SQLite")
        return None
    # postgresql:// faria o SQLAlchemy procurar o psycopg2; usamos o psycopg 3
    banco_url = re.sub(r"^postgres(ql)?://", "postgresql+psycopg://", banco_url)
    return create_engine(banco_url, pool_pre_ping=True)


def para_postgres(SCHEMA: str) -> str:
    """Adapta o DDL do sqlite_schema.py para o Postgres."""
    SCHEMA = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
                    "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", SCHEMA)
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", SCHEMA)


def carregar(df: pd.DataFrame, caminho_db: Path, tabela: str, SCHEMA) -> int:
    """Recria a tabela a partir do df. A planilha é a fonte da verdade, então
    rodar de novo substitui os dados em vez de duplicá-los. Tudo acontece numa
    única transação: se a inserção falhar, a tabela anterior é preservada.
    Depois do SQLite, grava a mesma tabela no Neon; uma falha lá só gera aviso."""
    caminho_db.parent.mkdir(parents=True, exist_ok=True)
    with closing(sqlite3.connect(caminho_db)) as conexao:
        with conexao:
            conexao.executescript(f"BEGIN; DROP TABLE IF EXISTS {tabela}; {SCHEMA}")
            df.to_sql(tabela, conexao, if_exists="append", index=False)
        total = conexao.execute(f"SELECT COUNT(*) FROM {tabela}").fetchone()[0]

    try:
        total_neon = carregar_neon(df, tabela, SCHEMA)
        if total_neon is not None:
            print(f"Tabela '{tabela}' agora tem {total_neon} registros no Neon")
    except Exception as erro:
        print(f"Aviso: falha ao gravar '{tabela}' no Neon: {erro}")

    return total


def carregar_neon(df: pd.DataFrame, tabela: str, SCHEMA) -> int | None:
    """Mesma lógica do SQLite: recria a tabela numa única transação (o Postgres
    também desfaz DROP/CREATE se algo falhar)."""
    engine = _engine_neon()
    if engine is None:
        return None
    with engine.begin() as conexao:
        conexao.execute(text(f"DROP TABLE IF EXISTS {tabela}"))
        for comando in para_postgres(SCHEMA).split(";"):
            if comando.strip():
                conexao.execute(text(comando))
        df.to_sql(tabela, conexao, if_exists="append", index=False, method="multi", chunksize=1000)
        return conexao.execute(text(f"SELECT COUNT(*) FROM {tabela}")).scalar()
